// Command prependlicense puts the repo's one-line SPDX license header at the top
// of every hand-written .go, .templ, .ts and .tsx file, and upgrades the 16-line
// Apache block the repo used before 2026-09 to that line. Generated code and
// dependency trees are skipped. It runs as the prepend-license pre-commit hook,
// from go/ (it locates the repo root through `go env GOMOD`).
package main

import (
	"context"
	"errors"
	"fmt"
	"io/fs"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"time"
)

// The header every hand-written source file starts with — the same line the
// .proto files carry (plan 09b), which protoc copies into the generated Go and
// TypeScript, so hand-written and generated code look alike. The copyright
// notice itself lives in the repo-root COPYRIGHT file.
const licenseLine = "// SPDX-License-Identifier: Apache-2.0"

// A file already carrying any SPDX tag is left alone.
const spdxTagPrefix = "// SPDX-License-Identifier:"

// The block header used until 2026-09: "See the file COPYRIGHT …" through
// "limitations under the License.", each end optionally wrapped in a bare "//"
// line. A file still carrying it (from an older branch, say) is rewritten to
// licenseLine, so the convention converges without anyone editing headers by hand.
const (
	legacyFirstLine = "// See the file COPYRIGHT for copyright information."
	legacyLastLine  = "// limitations under the License."
	legacyMaxLines  = 20
)

// Generated-code markers: protoc-gen-go, sqlc and templ emit "// Code generated
// by …"; protoc-gen-es emits "// @generated by …". Files carrying either are never
// stamped — generated output is git-ignored and produced at build time.
var generatedMarkers = []string{"// Code generated by", "// @generated by"}

// Conveniently, all of these take double-slash comments.
var stampedExts = map[string]bool{".go": true, ".templ": true, ".ts": true, ".tsx": true}

// Directories the walk never enters: dependencies and generated trees.
var skippedDirs = map[string]bool{".git": true, "node_modules": true, ".expo": true}

func main() {
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Minute)
	defer cancel()

	repo, err := os.OpenRoot(repoRoot(ctx))
	must(err)

	must(fs.WalkDir(repo.FS(), ".", func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			if skippedDirs[d.Name()] {
				return fs.SkipDir
			}
			return nil
		}
		if !stampedExts[filepath.Ext(d.Name())] {
			return nil
		}
		return stamp(repo, path)
	}))
}

// stamp rewrites one file so it starts with licenseLine, logging what it did.
func stamp(repo *os.Root, path string) error {
	contents, err := repo.ReadFile(path)
	if err != nil {
		return err
	}
	updated, what, err := withLicense(contents)
	if err != nil {
		return fmt.Errorf("%s: %w", path, err)
	}
	if what == "" {
		return nil
	}
	f, err := repo.Create(path)
	if err != nil {
		return err
	}
	_, err = f.Write(updated)
	if err != nil {
		_ = f.Close()
		return err
	}
	err = f.Close()
	if err != nil {
		return err
	}
	log.Printf("%s %s", what, path)
	return nil
}

// withLicense returns the file with the header in place and a phrase for the log
// ("Added the license header to", "Upgraded the license header in"); the phrase
// is empty, and the contents come back as they were, when there is nothing to do.
func withLicense(contents []byte) (updated []byte, what string, err error) {
	lines := strings.Split(string(contents), "\n")
	legacyAt := -1
	for i, line := range lines {
		if strings.HasPrefix(line, spdxTagPrefix) {
			return contents, "", nil
		}
		for _, marker := range generatedMarkers {
			if strings.HasPrefix(line, marker) {
				return contents, "", nil
			}
		}
		if legacyAt < 0 && strings.HasPrefix(line, legacyFirstLine) {
			legacyAt = i
		}
	}
	if legacyAt < 0 {
		return []byte(licenseLine + "\n\n" + string(contents)), "Added the license header to", nil
	}
	start, end, err := legacyBounds(lines, legacyAt)
	if err != nil {
		return nil, "", err
	}
	rest := lines[end+1:]
	out := make([]string, 0, len(lines))
	out = append(out, lines[:start]...)
	out = append(out, licenseLine)
	if len(rest) == 0 || strings.TrimSpace(rest[0]) != "" {
		out = append(out, "") // one blank line between the header and the code
	}
	out = append(out, rest...)
	return []byte(strings.Join(out, "\n")), "Upgraded the license header in", nil
}

// legacyBounds finds the lines the legacy block occupies around its first line:
// an optional bare "//" above, through legacyLastLine and an optional bare "//"
// below.
func legacyBounds(lines []string, first int) (start, end int, err error) {
	start = first
	if start > 0 && isBareComment(lines[start-1]) {
		start--
	}
	for end = first; end < len(lines) && end-first < legacyMaxLines; end++ {
		if !strings.HasPrefix(lines[end], legacyLastLine) {
			continue
		}
		if end+1 < len(lines) && isBareComment(lines[end+1]) {
			end++
		}
		return start, end, nil
	}
	return 0, 0, fmt.Errorf("the legacy license header at line %d has no %q line within %d lines",
		first+1, legacyLastLine, legacyMaxLines)
}

func isBareComment(line string) bool {
	return strings.TrimSpace(line) == "//"
}

// repoRoot is the git work tree, which holds every stamped tree: go/, the pnpm
// packages and playwright/. (The Go module's own directory — `go env GOMOD` —
// is one level down since plan 09f, so it is not the root to walk from.)
func repoRoot(ctx context.Context) string {
	cmd := exec.CommandContext(ctx, "git", "rev-parse", "--show-toplevel")
	out, err := cmd.Output()
	if err != nil {
		must(fmt.Errorf("finding the repo root with git rev-parse --show-toplevel: %w", err))
	}
	root := strings.TrimSpace(string(out))
	if root == "" {
		must(errors.New("git rev-parse --show-toplevel gave no repo root"))
	}
	return root
}

func must(err error) {
	if err != nil {
		panic(err)
	}
}
